export function t(lang: Lang, key: string): any {
  const get = (obj: any, path: string) => path.split('.').reduce((o, k) => (o && o[k] != null ? o[k] : undefined), obj)
  const v = get(messages[lang], key)
  if (v != null) return v
  return get(messages.fr, key)
}
